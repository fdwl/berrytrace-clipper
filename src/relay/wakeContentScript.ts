/**
 * 把已经被回收的 service worker **立刻**叫醒的那条路：用户打开的每一个网页。
 *
 * ── 它解决的是什么 ──────────────────────────────────────────────────────────
 * 李博 0907：「当用户打开浏览器，如何能够快速建立链接？这里是否可以自动连接插件，
 * 主动唤醒机制？**因为用户操作太快，插件还没有准备好，需要用户等一下的。**」
 *
 * 那个"等一下"是有确切来源的。MV3 下 service worker 空闲 30 秒就被回收，
 * 而在这个文件出现之前，能把它重新拉起来的东西只有两个：
 *   · `chrome.alarms` —— 最小周期 **30 秒**（`berrytraceRelay.ts` 的保活闹钟）
 *   · `chrome.tabs.onActivated` —— 只在**切换**标签时发，用户不切就不发
 * ⇒ 最坏情况用户要等满一个闹钟周期，而他这段时间里看到的是「没连上」。
 *
 * 而扩展**本来就有**一条匹配全部 http/https 站点的 content script
 * （上游的 content.js）—— 也就是说"用户打开任何网页"这个毫秒级的信号一直在，
 * 只是没有人拿它去叫醒 worker。这个文件就干这一件事。
 *
 * ⚠️ 注释里**不要抄 manifest 的通配写法**（那种 `http` 冒号双斜杠加两个星号的串）：
 *    它中间那两个字符正好是块注释的结束记号，会把这段注释从中间截断，
 *    后面半段变成语法错误的代码。〔0907 当场踩到，tsc 报了 20 条 TS1109/TS1127〕
 *    要说明匹配范围就用中文描述，跟 CLAUDE.md 七点五那条同一个道理。
 *
 * ── 为什么不写进上游那个 content.js ────────────────────────────────────────
 * 同 `background-entry.ts` 文件头那条：上游文件一个字都不动，
 * 否则每次合并 obsidian 上游都在一个高频文件上打架，
 * 而且 0826 踩过一次「源文件被还原时把接线一起还原掉，零报错」。
 *
 * ── 🔴 这个文件必须一直很小 ─────────────────────────────────────────────────
 * 它会被注入**用户访问的每一个页面**。除了发一条消息之外不许做任何事：
 * 不读 DOM、不建监听器、不 import 任何东西（import 会把整棵依赖树拖进每个页面）。
 * 失效条件：哪天 Chrome 给了扩展"进程外常驻"的能力，这个文件整个删掉。
 */

/**
 * 发一条空消息。**发出去这个动作本身就是目的** —— MV3 里
 * `chrome.runtime.sendMessage` 会把已回收的 service worker 拉起来，
 * 而 worker 一起来就会重新执行 `background-entry.ts`，中继随之重连。
 *
 * ⚠️ 回调必须读一次 `chrome.runtime.lastError`：没人接这条消息时它会置错，
 * 不读的话浏览器会往页面控制台打一条 "Unchecked runtime.lastError" ——
 * 出现在**用户自己的每一个网页**上，那是不可接受的噪音。
 */
try {
  chrome.runtime.sendMessage({ type: 'berrytrace-relay-wake' }, () => {
    void chrome.runtime.lastError;
  });
} catch {
  /*
   * 扩展正在重载 / 上下文已失效时会抛。这条路是"顺手叫一下"，
   * 叫不动完全不影响页面本身 —— 绝不能让它把用户的网页搞出错误。
   */
}
