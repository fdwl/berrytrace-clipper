/**
 * 守卫：**换了插件代码之后，之前就开着的页面还能不能重新装上工具条**
 *
 * ── 它为什么存在 ─────────────────────────────────────────────────────────
 * 李博 0907 连报两轮「录制中打开浏览器没有工具条」。第二轮定位到
 * 「浏览器一直跑着 8 月那个 service worker」，修法是让 App 自己叫
 * `chrome.runtime.reload()`。但**重载之后还有一半**：
 *
 * `chrome.runtime.reload()` **不会**卸掉页面里已经注入的 content script。
 * 那一份变成"孤儿"——JS 还在跑、监听器还在、DOM 还在，只是它手上的
 * `chrome.*` 已经失效（`Extension context invalidated`），
 * 于是它**再也收不到任何消息**。而浏览器也不会替我们往这些页面补一份新的。
 *
 * 头一版的守门是一个布尔 `if (w[FLAG]) return`：孤儿把那个布尔留在页面上，
 * 补注入进来的新一份当场 return ⇒ **用户看到的和"根本没装"一模一样**。
 * 这条测试钉的就是那个布尔被换成了"问一句你还活着吗"。
 *
 * ── 为什么判定是纯函数 ───────────────────────────────────────────────────
 * 〔实测〕`chrome.runtime.reload()` 在本机那套无头 + `--load-extension` 里
 * **复现不出来**：重载之后扩展的 service worker 再也没起来，等 150 秒、
 * 刷别的标签页去唤醒都不回来，`/json/list` 里连它的 target 都没了。
 * 而它在真浏览器里天天发生（李博的 Mac 上当场把两个浏览器换了代码）。
 * ⇒ 探测取决于浏览器，判定不该取决于浏览器（CLAUDE.md 六点六④）。
 */

import { describe, it, expect } from 'vitest';
import { 该接手吗 } from './recordContentScript';

const 活的 = { 活着: () => true, 拆: () => {} };
const 孤儿 = { 活着: () => false, 拆: () => {} };

describe('页面上已经有一份了，这一份怎么办', () => {
  it('干净的页面 ⇒ 接手', () => {
    expect(该接手吗(undefined)).toBe('take');
  });

  it('🔴 孤儿（扩展刚换过代码）⇒ 赶走它，自己接手 —— 少了这条，换完包的页面永远是空的', () => {
    expect(该接手吗(孤儿)).toBe('evict');
  });

  it('真的还活着 ⇒ 让位，不许挂第二条', () => {
    expect(该接手吗(活的)).toBe('yield');
  });

  it('🔴 「活着」和「孤儿」必须分辨得出来 —— 这正是那个布尔分辨不出的东西', () => {
    // 对照组：同一个位置上换一份活的，结论必须不同。
    // 少了这一条，函数恒回 'evict' 时上面那条也是绿的
    expect(该接手吗(孤儿)).not.toBe(该接手吗(活的));
  });

  it('旧版留下的布尔 ⇒ 保守让位（分辨不出死活时，宁可不挂第二条）', () => {
    expect(该接手吗(true)).toBe('yield');
    expect(该接手吗(false)).toBe('take');
  });

  it('🔴 「活着」这一问必须真的问到那一份自己身上 —— 不是问一个常量', () => {
    let 问过 = 0;
    该接手吗({ 活着: () => { 问过 += 1; return true; }, 拆: () => {} });
    expect(问过, '不问的话，孤儿和活的就又分不出来了').toBe(1);
  });
});
